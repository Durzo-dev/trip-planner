// tools/setup-hooks.mjs — installs the git hooks (npm run setup-hooks).
//
// Git does not version .git/hooks nor copy it on clone, so the hooks' bodies live here and this script
// writes them out (docs/en/versioning.md).
// - pre-commit: type check, then the test suite (design-system guards and version coherence included);
//   either failing refuses the commit with nothing touched. Then it bumps the patch and adds the files
//   carrying the version to the commit being made.
// - post-commit: when the commit changed the minor or major number, tags it vX.Y.Z (pushing the tag
//   publishes the release) and reminds that a plain git push does not send tags.
// Escape hatch for a work-in-progress commit: git commit --no-verify (no checks, no bump).
// Known limit: git commit --amend bumps again; amend with --no-verify.

import { chmodSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

export const PRE_COMMIT = `#!/bin/sh
# GENERATED by tools/setup-hooks.mjs — edit the template there, not here.
GITDIR=$(git rev-parse --git-dir)
# Replaying or combining existing commits: nothing new to check.
if [ -e "$GITDIR/MERGE_HEAD" ] || [ -d "$GITDIR/rebase-merge" ] || \\
   [ -d "$GITDIR/rebase-apply" ] || [ -e "$GITDIR/CHERRY_PICK_HEAD" ]; then
  exit 0
fi
if ! command -v npx > /dev/null 2>&1; then
  echo "pre-commit: npx not found in PATH, commit refused (bypass: git commit --no-verify)." >&2
  exit 1
fi
if ! npx --no-install tsc --noEmit; then
  echo "pre-commit: type errors, commit refused. Details: npm run typecheck" >&2
  exit 1
fi
if ! npx --no-install vitest run --silent > /dev/null 2>&1; then
  echo "pre-commit: the test suite fails, commit refused. Details: npm test" >&2
  exit 1
fi
# After the checks, so a failure leaves no bumped version without a commit
VERSION_OF() { sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p' | head -1; }
HEAD_V=$(git show HEAD:package.json 2>/dev/null | VERSION_OF)
WORK_V=$(VERSION_OF < package.json)
if node tools/bump-version.mjs should-auto-bump "$HEAD_V" "$WORK_V"; then
  node tools/bump-version.mjs patch || exit 1
else
  echo "pre-commit: version already set to $WORK_V by hand, no automatic bump."
fi
git add package.json package-lock.json README.md README.fr.md
`;

// After the commit, not before: at pre-commit the commit carrying the version does not exist yet. It
// cannot fail anything, the commit is made.
export const POST_COMMIT = `#!/bin/sh
# GENERATED by tools/setup-hooks.mjs — edit the template there, not here.
VERSION_OF() { sed -n 's/.*"version"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p' | head -1; }
PREV=$(git show HEAD~1:package.json 2>/dev/null | VERSION_OF)
CUR=$(git show HEAD:package.json 2>/dev/null | VERSION_OF)
[ -z "$PREV" ] && exit 0
[ -z "$CUR" ] && exit 0
TAG=$(node tools/bump-version.mjs tag-for "$PREV" "$CUR" 2>/dev/null)
[ -z "$TAG" ] && exit 0
if git rev-parse -q --verify "refs/tags/$TAG" > /dev/null; then
  echo "post-commit: tag $TAG already exists, left as it is." >&2
  exit 0
fi
if git tag -a "$TAG" -m "$TAG"; then
  echo ""
  echo "  Tag $TAG set on $(git rev-parse --short HEAD). A plain git push does NOT send tags:"
  echo "    git push --follow-tags"
  echo ""
fi
exit 0
`;

export const HOOKS = { "pre-commit": PRE_COMMIT, "post-commit": POST_COMMIT };

function main() {
  // Outside a git repository (a downloaded archive) there is nothing to install.
  if (!existsSync(join(ROOT, ".git"))) {
    console.log("No git repository here: no hook to install.");
    return;
  }
  const dir = join(ROOT, ".git", "hooks");
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  for (const [name, body] of Object.entries(HOOKS)) {
    const file = join(dir, name);
    writeFileSync(file, body);
    try {
      chmodSync(file, 0o755);
    } catch {
      // Windows: no executable bit, Git for Windows runs it anyway
    }
    console.log(`hook installed: ${name}`);
  }
}

if (process.argv[1]?.endsWith("setup-hooks.mjs")) main();
