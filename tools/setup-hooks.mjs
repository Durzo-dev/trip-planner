// tools/setup-hooks.mjs — installs the git hooks (npm run setup-hooks).
//
// Git does not version .git/hooks nor copy it on clone, so the hook's body lives here and this script
// writes it out. The pre-commit hook runs the type check and the test suite (design-system guards
// included) and refuses the commit if either fails. Escape hatch for a work-in-progress commit:
// git commit --no-verify.

import { chmodSync, existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

export const PRE_COMMIT = `#!/bin/sh
# GENERATED by tools/setup-hooks.mjs — edit the template there, not here.
GITDIR=$(git rev-parse --git-dir)
# Replaying or combining existing commits: nothing new to check.
if [ -e "$GITDIR/MERGE_HEAD" ] || [ -d "$GITDIR/rebase-merge" ] || \\
   [ -d "$GITDIR/rebase-apply" ] || [ -e "$GITDIR/CHERRY_PICK_HEAD" ]; then
  exit 0
fi
if ! command -v npx > /dev/null 2>&1; then
  echo "pre-commit: npx not found in PATH, commit refused (bypass: git commit --no-verify)." >&2
  exit 1
fi
if ! npx --no-install tsc --noEmit; then
  echo "pre-commit: type errors, commit refused. Details: npm run typecheck" >&2
  exit 1
fi
if ! npx --no-install vitest run --silent > /dev/null 2>&1; then
  echo "pre-commit: the test suite fails, commit refused. Details: npm test" >&2
  exit 1
fi
`;

function main() {
  // Outside a git repository (a downloaded archive) there is nothing to install.
  if (!existsSync(join(ROOT, ".git"))) {
    console.log("No git repository here: no hook to install.");
    return;
  }
  const dir = join(ROOT, ".git", "hooks");
  if (!existsSync(dir)) mkdirSync(dir, { recursive: true });
  const file = join(dir, "pre-commit");
  writeFileSync(file, PRE_COMMIT);
  try {
    chmodSync(file, 0o755);
  } catch {
    // Windows: no executable bit, Git for Windows runs it anyway
  }
  console.log("hook installed: pre-commit (type check + tests)");
}

if (process.argv[1]?.endsWith("setup-hooks.mjs")) main();
